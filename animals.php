/* ─────────────────────────────────────────
   SOUND PLAYBACK
───────────────────────────────────────── */
function showNoSound(card) {
    const existing = card.querySelector('.no-sound-toast');
    if (existing) existing.remove();
    const toast = document.createElement('div');
    toast.className = 'no-sound-toast';
    toast.innerHTML = '🔇 No sound available';
    card.appendChild(toast);
    requestAnimationFrame(() => toast.classList.add('show'));
    setTimeout(() => {
        toast.classList.remove('show');
        setTimeout(() => toast.remove(), 300);
    }, 2000);
}

function playSound(name, card) {
    card.classList.remove('playing');
    void card.offsetWidth;
    card.classList.add('playing');
    card.addEventListener('animationend', () => card.classList.remove('playing'), { once: true });

    if (currentAudio) { currentAudio.pause(); currentAudio.currentTime = 0; currentAudio = null; }

    const enName = tlToEn[name] || name;
    const url = animalSounds[enName];

    if (!url) { showNoSound(card); return; }

    const audio = new Audio(url);
    audio.volume = 0.85;
    audio.addEventListener('error', () => showNoSound(card), { once: true });
    audio.play()
        .then(() => { currentAudio = audio; confetti(catColors[card.dataset.category] || '#888'); })
        .catch(() => showNoSound(card));
}

/* ─────────────────────────────────────────
   CONFETTI
───────────────────────────────────────── */
function confetti(color) {
    const cols = [color,'#FFE66D','#FF6B6B','#A29BFE','#4ECDC4','#FD79A8'];
    for (let i = 0; i < 20; i++) {
        const p = document.createElement('div'); p.className = 'cp';
        p.style.cssText = `left:${Math.random()*100}vw;top:-10px;background:${cols[Math.floor(Math.random()*cols.length)]};border-radius:${Math.random()>.5?'50%':'2px'};width:${5+Math.random()*7}px;height:${5+Math.random()*7}px;animation-duration:${1+Math.random()*1.2}s;animation-delay:${Math.random()*.3}s;`;
        document.body.appendChild(p);
        p.addEventListener('animationend', () => p.remove());
    }
}

