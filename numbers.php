    function doCountIn() {
      const raw = parseInt(kpadVal);
      if (isNaN(raw) || raw < 1 || raw > 100) {
        const disp = document.getElementById('bcInputDisplay');
        disp.style.borderColor = '#FF6B6B';
        disp.style.background = 'rgba(255,100,100,.2)';
        setTimeout(() => {
