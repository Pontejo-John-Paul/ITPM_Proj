      function step() {
        if (!bcRunning) return;
        bcCurrent++;
        const b = makeBalloon(bcCurrent, '0s');
        grid.appendChild(b);
        b.scrollIntoView({
          behavior: 'smooth',
          block: 'nearest'
        });
        setBcBig(bcCurrent);
        document.getElementById('bcWord').textContent = UI[lang].word(bcCurrent);
        document.getElementById('bcBadgeTxt').textContent = UI[lang].badge(bcCurrent);
        document.getElementById('bcProg').style.width = ((bcCurrent / bcTarget) * 100) + '%';

        const word = UI[lang].word(bcCurrent) || String(bcCurrent);
        const lc = lang === 'en' ? 'en-US' : 'fil-PH';
        if (bcCurrent < bcTarget) {
          speakThenNext(word, lc, step);
        } else {
          speakThenNext(word, lc, () => {
            bcRunning = false;
            bcPaused = false;
            document.getElementById('bcStatus').textContent = UI[lang].statusDone(bcTarget);
            document.getElementById('bcStartBtn').style.display = '';
            document.getElementById('bcPauseBtn').style.display = 'none';
          });
        }
      }
      step();
    }

