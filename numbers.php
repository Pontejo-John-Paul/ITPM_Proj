    function playVid(tab, idx) {
      const key = tab + idx;

      // Stop the currently playing video if it exists
      if (currentPlayingVid !== null && currentPlayingVid !== key) {
        const prevSuffix = currentPlayingVid.charAt(0).toUpperCase() + currentPlayingVid.slice(1) + currentPlayingVid.slice(-1);
        const prevFrame = document.getElementById('vframe' + prevSuffix);
        const prevOverlay = document.getElementById('voverlay' + prevSuffix);

        if (prevFrame) {
          prevFrame.src = '';
          prevFrame.style.display = 'none';
        }
        if (prevOverlay) {
          prevOverlay.classList.remove('gone');
        }
        vPlaying[currentPlayingVid] = false;
      }

      if (vPlaying[key]) return;
      vPlaying[key] = true;
      currentPlayingVid = key;

      const suffix = tab.charAt(0).toUpperCase() + tab.slice(1) + idx;
      const videoId = VIDS[tab][idx].id;
      const overlay = document.getElementById('voverlay' + suffix);

      // Set thumbnail background image
      overlay.style.backgroundImage = `url('https://img.youtube.com/vi/${videoId}/maxresdefault.jpg')`;

      document.getElementById('vframe' + suffix).src =
        `https://www.youtube-nocookie.com/embed/${videoId}?autoplay=1&rel=0&modestbranding=1&playsinline=1`;
      document.getElementById('vframe' + suffix).style.display = 'block';
      overlay.classList.add('gone');
    }

