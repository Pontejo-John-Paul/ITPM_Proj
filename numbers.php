          disp.style.background = 'rgba(255,255,255,.12)';
        }, 800);
        return;
      }
      stopBC();
      bcTarget = raw;
      startCounting();
    }

    function startCounting() {
      if (bcRunning || bcTarget === 0) return;
      bcRunning = true;
      bcPaused = false;
      bcCurrent = 0;
      document.getElementById('bcStatus').textContent = UI[lang].statusCount(bcTarget);
      const grid = document.getElementById('bcGrid');
