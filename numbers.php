    function safeSpeak(text, langCode) {
      if (!window.speechSynthesis) return;
      window.speechSynthesis.cancel();
      setTimeout(() => {
        const u = new SpeechSynthesisUtterance(text);
        u.lang = langCode;
        u.rate = .88;
        u.pitch = 1.15;
        u.volume = 1;
        window.speechSynthesis.speak(u);
      }, 50);
    }
    /* Speak a word, then call callback only after speech ends */
    function speakThenNext(text, langCode, callback) {
      if (!window.speechSynthesis) {
        bcTimer = setTimeout(callback, 1000);
        return;
      }
      window.speechSynthesis.cancel();
      setTimeout(() => {
        if (!bcRunning) return;
        const u = new SpeechSynthesisUtterance(text);
        u.lang = langCode;
        u.rate = .88;
        u.pitch = 1.15;
        u.volume = 1;
        u.onend = () => {
          if (bcRunning) bcTimer = setTimeout(callback, 300);
        };
        u.onerror = () => {
          if (bcRunning) bcTimer = setTimeout(callback, 300);
        };
        window.speechSynthesis.speak(u);
      }, 80);
    }

